"""Regenerate the files Dev A builds against from backend/app/models.py.

    cd backend && python scripts/export_contract.py

Writes:
  fixtures/schema.json          JSON Schema for every API body and response
  lovable/src/lib/contract.ts   TypeScript types for the Lovable app
  lovable/src/lib/fixtures.ts   the demo runs as typed TypeScript data
"""

from __future__ import annotations

import json
import sys
import types
import typing
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))

from pydantic import BaseModel  # noqa: E402
from pydantic.json_schema import models_json_schema  # noqa: E402

from app import models as contract  # noqa: E402
from app.store import FIXTURE_FILES, FIXTURES_DIR  # noqa: E402
from app.models import (  # noqa: E402
    SCHEMA_VERSION,
    ApproveRequest,
    EvalResult,
    ExperimentDecision,
    ResultCreate,
    RunContext,
    RunCreate,
    RunCreated,
    RunState,
)

FIXTURES = {
    state.run.id: state
    for state in (
        RunState.model_validate_json((FIXTURES_DIR / name).read_text(encoding="utf-8")) for name in FIXTURE_FILES
    )
}

LOVABLE_LIB = ROOT / "lovable" / "src" / "lib"
GENERATED_TS = "// Generated by backend/scripts/export_contract.py from backend/app/models.py. Do not edit."
# Request bodies: fields with a default may be left out, so they become optional (`?`) in TS.
REQUEST_MODELS = {RunCreate, RunContext, ApproveRequest, ExperimentDecision, ResultCreate}
_SCALARS = {str: "string", int: "number", float: "number", bool: "boolean", datetime: "string"}


def export_schema() -> Path:
    _, schema = models_json_schema(
        [
            (RunCreate, "validation"),
            (RunCreated, "serialization"),
            (RunState, "serialization"),
            (ApproveRequest, "validation"),
            (ResultCreate, "validation"),
            (EvalResult, "serialization"),
        ],
        title=f"Lab-to-Market contract v{SCHEMA_VERSION}",
    )
    out = ROOT / "fixtures" / "schema.json"
    out.write_text(json.dumps(schema, indent=2) + "\n", encoding="utf-8")
    return out


def _literal_aliases() -> dict[tuple, str]:
    return {
        typing.get_args(obj): name
        for name, obj in vars(contract).items()
        if typing.get_origin(obj) is typing.Literal
    }


def _ts_type(tp: object, aliases: dict[tuple, str]) -> str:
    origin, args = typing.get_origin(tp), typing.get_args(tp)
    if tp is type(None):
        return "null"
    if origin is typing.Literal:
        return aliases.get(args) or " | ".join(json.dumps(a) for a in args)
    if origin in (typing.Union, types.UnionType):
        return " | ".join(_ts_type(a, aliases) for a in args)
    if origin is list:
        inner = _ts_type(args[0], aliases)
        return f"({inner})[]" if " | " in inner else f"{inner}[]"
    if origin is dict:
        return f"Record<{_ts_type(args[0], aliases)}, {_ts_type(args[1], aliases)}>"
    if isinstance(tp, type) and issubclass(tp, BaseModel):
        return tp.__name__
    return _SCALARS[tp]


def export_typescript() -> list[Path]:
    aliases = _literal_aliases()
    lines = [GENERATED_TS, "", f"export const SCHEMA_VERSION = {SCHEMA_VERSION};", ""]
    for args, name in aliases.items():
        lines.append(f"export type {name} = {' | '.join(json.dumps(a) for a in args)};")
    for model in vars(contract).values():
        if not (isinstance(model, type) and issubclass(model, contract.Contract)):
            continue
        if model is contract.Contract:
            continue
        lines.append("")
        if model.__doc__ and model.__doc__ != BaseModel.__doc__:
            lines.append(f"/** {model.__doc__.strip().splitlines()[0]} */")
        lines.append(f"export interface {model.__name__} {{")
        for field_name, field in model.model_fields.items():
            optional = model in REQUEST_MODELS and not field.is_required()
            ts = _ts_type(field.annotation, aliases)
            lines.append(f"  {field_name}{'?' if optional else ''}: {ts};")
        lines.append("}")
    contract_ts = LOVABLE_LIB / "contract.ts"
    contract_ts.parent.mkdir(parents=True, exist_ok=True)
    contract_ts.write_text("\n".join(lines) + "\n", encoding="utf-8")

    data = {run_id: state.model_dump(mode="json") for run_id, state in FIXTURES.items()}
    fixtures_ts = LOVABLE_LIB / "fixtures.ts"
    fixtures_ts.write_text(
        "\n".join(
            [
                GENERATED_TS,
                "// Demo runs. Every number here is invented; never present them as real data.",
                'import type { RunState } from "./contract";',
                "",
                f"export const FIXTURES: Record<string, RunState> = {json.dumps(data, indent=2, ensure_ascii=False)};",
                "",
            ]
        ),
        encoding="utf-8",
    )
    return [contract_ts, fixtures_ts]


if __name__ == "__main__":
    for path in (export_schema(), *export_typescript()):
        print(f"wrote {path.relative_to(ROOT)}")
